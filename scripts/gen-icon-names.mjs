// Regenerates assets/js/icon-names.js (the list used by icons.html) from the
// icon catalog in assets/icons/regular. Run: npm run icons:names
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "assets/icons/regular");
const names = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".svg"))
  .map((f) => f.slice(0, -4))
  .sort();

const css = fs.readFileSync(path.join(root, "src/input.css"), "utf8");
const missing = names.filter((n) => !css.includes(`.kk-${n} {`));
if (missing.length) {
  console.error(`No .kk-${missing[0]} class in src/input.css (${missing.length} missing). Regenerate the icon tokens first.`);
  process.exit(1);
}

const out = `/* GENERATED by scripts/gen-icon-names.mjs - do not edit by hand.
   ${names.length} icons; each has 6 weights (thin, light, regular, bold, fill, duotone). */
window.KK_ICON_NAMES = ${JSON.stringify(names)};
`;
fs.writeFileSync(path.join(root, "assets/js/icon-names.js"), out);
console.log(`icon-names.js: ${names.length} icons`);
