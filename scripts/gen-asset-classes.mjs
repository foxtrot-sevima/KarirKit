// Regenerates src/asset-classes.css (and stories/Foundations/asset-names.js): the kk-flag-*, kk-pay-*, kk-brand-* and kk-file-* classes
// for the full-colour assets in assets/flags and assets/misc-icons. Run: npm run assets:classes
// Unlike the one-colour .kk-* icons these keep their own colours, so they are painted as
// background-image (url() is not subject to the CORS rule that forces data URIs for mask-image).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const list = (dir, suffix) =>
  fs.readdirSync(path.join(root, dir)).filter((f) => f.endsWith(suffix)).sort();
const url = (dir, file) => `url("../assets/${dir}/${encodeURI(file)}")`;

const rules = [];
const counts = {};

// Flags: assets/flags/<iso>.svg  ->  .kk-flag-<iso>
const flags = list("assets/flags", ".svg").map((f) => f.slice(0, -4));
flags.forEach((c) => rules.push(`  .kk-flag-${c} { background-image: ${url("flags", c + ".svg")}; }`));
counts.flags = flags.length;

// Payment logos: <name>-large.svg is the master (the smaller sizes are the same artwork)
const pay = list("assets/misc-icons/payment", "-large.svg").map((f) => f.slice(0, -"-large.svg".length));
pay.forEach((n) => rules.push(`  .kk-pay-${n} { background-image: ${url("misc-icons/payment", n + "-large.svg")}; }`));
counts.pay = pay.length;

// Brand logos: .kk-brand-<name> is the original colours; add kk-brand-black | white | disabled to change the tone
const TONES = ["black", "white", "disabled"];
const brands = list("assets/misc-icons/brand-logo", "-original.svg").map((f) => f.slice(0, -"-original.svg".length));
brands.forEach((n) => {
  rules.push(`  .kk-brand-${n} { background-image: ${url("misc-icons/brand-logo", n + "-original.svg")}; }`);
  TONES.forEach((t) =>
    rules.push(`  .kk-brand-${t}.kk-brand-${n} { background-image: ${url("misc-icons/brand-logo", `${n}-${t}.svg`)}; }`)
  );
});
counts.brand = brands.length;

// File types: .kk-file-<type> is the default look; add kk-file-gray | solid for the other two.
// pdf-1 / video-1 become kk-file-pdf / kk-file-video, the -2 variants keep their number.
const FTONES = ["gray", "solid"];
const files = list("assets/misc-icons/files", "-default.svg").map((f) => f.slice(0, -"-default.svg".length));
files.forEach((n) => {
  const cls = n.replace(/-1$/, "");
  rules.push(`  .kk-file-${cls}:not(.kk) { background-image: ${url("misc-icons/files", n + "-default.svg")}; }`);
  FTONES.forEach((t) =>
    rules.push(`  .kk-file-${t}.kk-file-${cls}:not(.kk) { background-image: ${url("misc-icons/files", `${n}-${t}.svg`)}; }`)
  );
});
counts.file = files.length;

// App logos: .kk-app-<name> is the primary (brand colour) look; kk-app-white | disabled switch the tone.
// A tone is skipped when the source has no file for it (siakadcloud has no disabled version).
// "google meet" has a space in its file name; the class uses a hyphen.
const ATONES = ["white", "disabled"];
const appDir = "assets/misc-icons/application";
const apps = list(appDir, "-primary.svg").map((f) => f.slice(0, -"-primary.svg".length));
apps.forEach((n) => {
  const cls = n.replace(/ /g, "-");
  rules.push(`  .kk-app-${cls} { background-image: ${url("misc-icons/application", n + "-primary.svg")}; }`);
  ATONES.filter((t) => fs.existsSync(path.join(root, appDir, `${n}-${t}.svg`))).forEach((t) =>
    rules.push(`  .kk-app-${t}.kk-app-${cls} { background-image: ${url("misc-icons/application", `${n}-${t}.svg`)}; }`)
  );
});
counts.app = apps.length;

// every referenced file must exist
const missing = rules
  .map((r) => decodeURI(r.match(/url\("\.\.\/([^"]+)"\)/)[1]))
  .filter((p) => !fs.existsSync(path.join(root, p)));
if (missing.length) {
  console.error("Missing asset files:\n" + missing.join("\n"));
  process.exit(1);
}

const out = `/* GENERATED by scripts/gen-asset-classes.mjs - do not edit by hand.
   Full-colour assets: ${counts.flags} flags, ${counts.pay} payment logos, ${counts.brand} brand logos (4 tones), ${counts.app} app logos (primary, white, disabled), ${counts.file} file types (3 looks).
   Size with font-size (text-2xl, ...) or with h-* w-* utilities, which win over these defaults.
     <span class="kk-flag kk-flag-id"></span>
     <span class="kk-pay kk-pay-visa"></span>
     <span class="kk-brand kk-brand-github kk-brand-white"></span>
     <span class="kk-app kk-app-siakadcloud kk-app-white"></span>
     <span class="kk-file kk-file-pdf kk-file-gray"></span> */
@layer components {
  /* kk-flag and kk-file are also Phosphor icon names (<i class="kk kk-flag">, kk-file-pdf, ...), so every
     rule here skips elements that carry the icon base class .kk */
  .kk-flag:not(.kk), .kk-pay, .kk-brand, .kk-app, .kk-file:not(.kk) {
    display: inline-block;
    height: 1em;
    flex-shrink: 0;
    vertical-align: -0.125em;
    background-repeat: no-repeat;
    background-position: center;
    background-size: contain;
    -webkit-mask-image: none;
    mask-image: none;
  }
  .kk-flag:not(.kk) { width: 1.3333em; }
  .kk-pay { width: 1.45em; }
  .kk-brand, .kk-app, .kk-file:not(.kk) { width: 1em; }

${rules.join("\n")}
}
`;
fs.writeFileSync(path.join(root, "src/asset-classes.css"), out);

// Name lists for the Foundations/Assets story (stories/Foundations/asset-names.js)
const fileNames = files.map((n) => n.replace(/-1$/, ""));
const names = `// GENERATED by scripts/gen-asset-classes.mjs - do not edit by hand.
export const FLAGS = ${JSON.stringify(flags)};
export const PAY = ${JSON.stringify(pay)};
export const BRAND = ${JSON.stringify(brands)};
export const APP = ${JSON.stringify(apps.map((n) => n.replace(/ /g, "-")))};
export const APP_NO_DISABLED = ${JSON.stringify(apps.filter((n) => !fs.existsSync(path.join(root, appDir, n + "-disabled.svg"))).map((n) => n.replace(/ /g, "-")))};
export const FILE = ${JSON.stringify(fileNames)};
`;
fs.writeFileSync(path.join(root, "stories/Foundations/asset-names.js"), names);
console.log(`asset-classes.css: ${rules.length} rules`, counts);
